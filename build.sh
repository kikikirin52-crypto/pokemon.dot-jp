#!/bin/bash

# ポケモン構築補完システム - ビルドスクリプト (Bash)

echo ""
echo "╔════════════════════════════════════════════════════════╗"
echo "║   ポケモン構築補完システム - ビルド開始                  ║"
echo "╚════════════════════════════════════════════════════════╝"
echo ""

# チェック: Node.js がインストールされているか
if ! command -v node &> /dev/null; then
    echo "❌ エラー: Node.js がインストールされていません"
    exit 1
fi

echo "✓ Node.js: $(node -v)"
echo "✓ npm: $(npm -v)"
echo ""

# ステップ1: フロントエンドのビルド
echo "════════════════════════════════════════════════════════"
echo "ステップ1: フロントエンドをビルド中..."
echo "════════════════════════════════════════════════════════"
echo ""

cd frontend

if [ ! -d "node_modules" ]; then
    echo "フロントエンド依存パッケージをインストール中..."
    npm install
    if [ $? -ne 0 ]; then
        echo "❌ フロントエンド依存パッケージのインストールに失敗しました"
        exit 1
    fi
fi

echo "フロントエンドをビルド中..."
npm run build
if [ $? -ne 0 ]; then
    echo "❌ フロントエンドのビルドに失敗しました"
    cd ..
    exit 1
fi

cd ..
echo "✓ フロントエンドのビルド完了"
echo ""

# ステップ2: ビルド結果をバックエンドにコピー
echo "════════════════════════════════════════════════════════"
echo "ステップ2: ビルド結果をバックエンドにコピー中..."
echo "════════════════════════════════════════════════════════"
echo ""

# backend/public ディレクトリを作成
mkdir -p backend/public

# フロントエンドのビルド結果をコピー
echo "frontend/build から backend/public にコピー中..."
cp -r frontend/build/* backend/public/
echo "✓ コピー完了"
echo ""

# ステップ3: バックエンド依存パッケージの確認
echo "════════════════════════════════════════════════════════"
echo "ステップ3: バックエンド依存パッケージの確認..."
echo "════════════════════════════════════════════════════════"
echo ""

cd backend

if [ ! -d "node_modules" ]; then
    echo "バックエンド依存パッケージをインストール中..."
    npm install
    if [ $? -ne 0 ]; then
        echo "❌ バックエンド依存パッケージのインストールに失敗しました"
        exit 1
    fi
fi

cd ..
echo "✓ バックエンド依存パッケージの確認完了"
echo ""

# 完成
echo "╔════════════════════════════════════════════════════════╗"
echo "║          ✓ ビルド完了！                                ║"
echo "╚════════════════════════════════════════════════════════╝"
echo ""
echo "本番環境での起動コマンド:"
echo "  cd backend"
echo "  NODE_ENV=production npm start"
echo ""
